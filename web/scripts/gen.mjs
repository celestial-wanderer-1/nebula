// Generates TypeScript from proto/ (D25) and builds the fake plugin
// FileDescriptorSet fixture, as binary and as a base64 module the mock backend
// can import in the browser. Runs from the repository root, where buf.yaml lives.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const web = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const root = resolve(web, "..");
const buf = join(web, "node_modules", ".bin", "buf");
const run = (args) => execFileSync(buf, args, { cwd: root, stdio: "inherit" });

run(["lint"]);
run(["generate"]);
mkdirSync(join(web, "src", "mocks", "fixtures"), { recursive: true });
// A plugin ships only its own files; core files are excluded (A§5.4).
run([
  "build",
  "web/test-fixtures/proto",
  "--exclude-imports",
  "--exclude-source-info",
  "-o",
  "web/src/mocks/fixtures/acme-demo.binpb",
]);

const fixture = join(web, "src", "mocks", "fixtures", "acme-demo");
writeFileSync(
  `${fixture}.ts`,
  `// Generated by scripts/gen.mjs. Do not edit.\nexport const acmeDemoDescriptorSet =\n  "${readFileSync(`${fixture}.binpb`).toString("base64")}";\n`,
);
